/** Observable review contract: acceptance, dependency-scoped revisions and safe retries. */
import { afterEach, expect, test, vi } from "vitest";
import { reviewCsv } from "../export";
import { createDemoService } from "./service";

afterEach(() => vi.useRealTimers());

test("correction preserves earlier evidence, changes only dependents, and deduplicates confirmation", async () => {
  vi.useFakeTimers({ shouldAdvanceTime: true });
  const { service, controls } = createDemoService();
  const before = await service.getRun("oa6-1rk");
  const accepted = await service.acceptCheck(
    "oa6-1rk",
    "r1",
    "trabecular",
    "trab-boundary",
  );
  expect(accepted.revisions[0].tasks[3].checks[0].status).toBe("accepted");
  expect(accepted.revisions[0].tasks[3].measurements).toEqual(
    before.revisions[0].tasks[3].measurements,
  );
  const request = {
    runId: "oa6-1rk",
    baseRevisionId: "r1",
    taskId: "trabecular",
    instruction: "Move the medial boundary by two voxels",
  };
  const proposal = await service.proposeCorrection(request);
  const stale = await service.proposeCorrection({
    ...request,
    taskId: "femur",
  });
  expect(proposal.affectedTaskIds).toEqual(["trabecular", "plate"]);
  expect((await service.getRun("oa6-1rk")).revisions).toHaveLength(1);
  controls.failNextRerun();
  await expect(service.confirmCorrection(proposal.id)).rejects.toThrow(
    "earlier result is safe",
  );
  expect((await service.getRun("oa6-1rk")).revisions).toEqual(
    accepted.revisions,
  );
  const [first, duplicate] = await Promise.all([
    service.confirmCorrection(proposal.id),
    service.confirmCorrection(proposal.id),
  ]);
  expect(first.revisions).toHaveLength(2);
  expect(duplicate).toEqual(first);
  expect(first.revisions[0]).toEqual(accepted.revisions[0]);
  expect(first.revisions[1].tasks.slice(0, 3)).toEqual(
    accepted.revisions[0].tasks.slice(0, 3),
  );
  expect(
    first.revisions[1].tasks[3].measurements.find((m) => m.id === "trab-th"),
  ).toMatchObject({ value: 103, origin: "synthetic", status: "provisional" });
  expect(first.revisions[1].tasks[3].checks[0].status).toBe("open");
  expect(first.revisions[1].tasks[3].evidence[0]).toMatchObject({
    url: null,
    unavailableReason: "No new evidence was generated by the simulated rerun.",
  });
  await expect(service.confirmCorrection(stale.id)).rejects.toThrow(
    "superseded",
  );
  await expect(
    service.acceptCheck("oa6-1rk", "r1", "femur", "landmark-a"),
  ).rejects.toThrow("superseded");
}, 12000);

test("questions stay task-scoped, load failure is recoverable, and invalid instructions do not mutate results", async () => {
  vi.useFakeTimers({ shouldAdvanceTime: true });
  const { service, controls } = createDemoService();
  const answered = await service.ask(
    "oa6-1rk",
    "r1",
    "iioc",
    "Why is the boundary uncertain?",
  );
  expect(answered.revisions[0].tasks[2].messages).toHaveLength(2);
  expect(
    answered.revisions[0].tasks
      .filter((t) => t.id !== "iioc")
      .every((t) => t.messages.length === 0),
  ).toBe(true);
  controls.failNextLoad();
  await expect(service.getRun("oa6-1rk")).rejects.toThrow("connection failure");
  expect(await service.getRun("oa6-1rk")).toEqual(answered);
  const proposal = await service.proposeCorrection({
    runId: "oa6-1rk",
    baseRevisionId: "r1",
    taskId: "iioc",
    instruction: "Adjust the region",
  });
  expect(proposal.affectedTaskIds).toEqual(["iioc", "trabecular", "plate"]);
  await expect(
    service.proposeCorrection({
      runId: "oa6-1rk",
      baseRevisionId: "r1",
      taskId: "femur",
      instruction: "  ",
    }),
  ).rejects.toThrow();
  expect((await service.getRun("oa6-1rk")).revisions).toEqual(
    answered.revisions,
  );
});

test("CSV retains provenance, missing cells, quotes, and spreadsheet formula safety", async () => {
  const { service } = createDemoService();
  const run = await service.getRun("oa6-1rk");
  run.revisions[0].tasks[0].title = '=HYPERLINK("example")';
  const csv = reviewCsv(run, run.revisions[0]);
  expect(csv).toContain('"\'=HYPERLINK(""example"")"');
  expect(csv).toContain(
    '"Patella core volume","","mm³","provisional","unavailable"',
  );
  expect(csv).toContain(
    '"Trabecular thickness (Tb.Th)","97.6","µm","provisional","documented","trab-spheres","true"',
  );
});
